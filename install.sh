#!/usr/bin/env bash
# NeoExit installer for Ubuntu / Debian.
#
#   curl -fsSL https://raw.githubusercontent.com/neoauroraproject/neoexit/main/install.sh | sudo bash
#
# Options (after "bash -s --" when piping):
#   --version vX.Y.Z  install a specific release (default: latest)
#   --binary PATH     install from a binary you already downloaded
#   --upgrade         upgrade without opening the menu
#   --uninstall       remove NeoExit and its settings
#
# Run again in a terminal on a server that has NeoExit, it opens the menu
# (update, new password, uninstall...); otherwise it installs or upgrades,
# keeping the settings and password.
set -euo pipefail

REPO="neoauroraproject/neoexit"
VERSION="latest" BINARY="" UNINSTALL=0 MENU=1

while [ $# -gt 0 ]; do
  case "$1" in
    --version) VERSION="$2"; MENU=0; shift ;;
    --binary) BINARY="$2"; MENU=0; shift ;;
    --upgrade) MENU=0 ;;
    --uninstall) UNINSTALL=1 ;;
    -h|--help) sed -n '2,15p' "$0" 2>/dev/null || true; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

c_ok=$'\033[38;5;78m' c_dim=$'\033[2m' c_acc=$'\033[38;5;36m' c_err=$'\033[38;5;203m' c_0=$'\033[0m'
step() { printf '%s›%s %s\n' "$c_acc" "$c_0" "$*"; }
ok()   { printf '%s✓%s %s\n' "$c_ok" "$c_0" "$*"; }
die()  { printf '%s✗ %s%s\n' "$c_err" "$*" "$c_0" >&2; exit 1; }

# >>> neo-ui · generated by neoproject/brand/cli, edit there >>>
NEO_NAME='NeoExit' NEO_SLUG='neoexit' NEO_ACCENT=221
NEO_BANNER=$(cat <<'NEO_BANNER_EOF'
   _  __            ____       _  __
  / |/ /___  ___   / __/__ __ (_)/ /_
 /    // -_)/ _ \ / _/  \ \ // // __/
/_/|_/ \__/ \___//___/ /_\_\/_/ \__/
NEO_BANNER_EOF
)
# NeoProject terminal UI: banner, NeoTunnel-style arrow menu, prompts and the
# RTL ad box. Needs bash 4+. Set before use: NEO_NAME, NEO_SLUG, NEO_ACCENT
# (256-colour number), NEO_BANNER; optional NEO_ADS_SOURCES, NEO_NO_ADS=1.
# Questions and keys are read from /dev/tty, so it all works under
# "curl ... | sudo bash".

NEO_SITE="${NEO_SITE:-neoproject.dev}"
NEO_ADS_SOURCES="${NEO_ADS_SOURCES:-https://api.neoproject.dev/v1/ads https://license.hossein-m466.workers.dev/v1/ads}"

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  _n0=$'\033[0m' _nB=$'\033[1m' _nD=$'\033[2m' _nA=$'\033[38;5;'"${NEO_ACCENT:-44}"'m'
  _nG=$'\033[38;5;78m' _nY=$'\033[38;5;221m' _nR=$'\033[38;5;203m'
else
  _n0='' _nB='' _nD='' _nA='' _nG='' _nY='' _nR=''
fi

neo_step() { printf '%s›%s %s\n' "$_nA" "$_n0" "$*"; }
neo_ok()   { printf '%s✓%s %s\n' "$_nG" "$_n0" "$*"; }
neo_warn() { printf '%s!%s %s\n' "$_nY" "$_n0" "$*"; }
neo_err()  { printf '%s✗ %s%s\n' "$_nR" "$*" "$_n0" >&2; }
neo_die()  { neo_err "$*"; exit 1; }

# neo_tty: true when someone is at a keyboard we can read from.
neo_tty() { [ -t 1 ] && { : </dev/tty; } 2>/dev/null; }

neo_cols() {
  local c=""
  c=$({ stty size </dev/tty; } 2>/dev/null | awk '{print $2}') || true
  [ -n "$c" ] || c=$(tput cols 2>/dev/null) || true
  [[ "$c" =~ ^[0-9]+$ ]] && [ "$c" -gt 20 ] || c=80
  printf '%s' "$c"
}

neo_rule() {
  local w; w=$(neo_cols); [ "$w" -gt 66 ] && w=66
  local line; printf -v line '%*s' $((w - 2)) ''
  printf ' %s%s%s\n' "$_nD" "${line// /─}" "$_n0"
}

# neo_banner [version] [subtitle]: the product's ASCII name, then one line
# with version and site, then a rule (the NeoTunnel menu header).
neo_banner() {
  printf '\n%s%s%s\n' "$_nA" "$NEO_BANNER" "$_n0"
  printf ' %s◆ %s%s' "$_nA" "$NEO_NAME" "$_n0"
  [ -n "${1:-}" ] && printf ' %s%s%s' "$_nD" "$1" "$_n0"
  [ -n "${2:-}" ] && printf '  %s%s' "$2" "$_n0"
  printf '   %s%s%s\n' "$_nD" "$NEO_SITE" "$_n0"
  neo_rule
}

# _neo_w: display width of a string (UTF-8 aware, Persian included).
_neo_w() { local LC_ALL=C.UTF-8 s="$1"; printf '%s' "${#s}"; }
_neo_cut() { # text width → text cut to width, with … when cut
  local LC_ALL=C.UTF-8 s="$1" n="$2"
  if [ "${#s}" -gt "$n" ] && [ "$n" -gt 1 ]; then printf '%s…' "${s:0:$((n - 1))}"; else printf '%s' "$s"; fi
}

# neo_menu TITLE "Label|hint" ... → NEO_CHOICE = 1..N, or 0 for back/exit.
# ↑/↓ (or k/j) move, Enter picks, digits pick directly, 0 / q / Esc / ← go back.
neo_menu() {
  local title="$1"; shift
  local -a L=() H=()
  local it
  for it in "$@"; do
    L+=("${it%%|*}")
    if [[ "$it" == *"|"* ]]; then H+=("${it#*|}"); else H+=(""); fi
  done
  local n=${#L[@]} sel=0 lw=0 i w
  NEO_CHOICE=0
  for i in "${!L[@]}"; do w=$(_neo_w "${L[$i]}"); [ "$w" -gt "$lw" ] && lw=$w; done

  if ! neo_tty; then # no arrow keys: a numbered list; never read stdin (it may be the script)
    printf '\n %s\n\n' "$title"
    for i in "${!L[@]}"; do printf '  %2d) %s\n' $((i + 1)) "${L[$i]}"; done
    printf '   0) Back\n\n  Choose: '
    local a=""; { IFS= read -r a </dev/tty; } 2>/dev/null || true; echo
    [[ "$a" =~ ^[0-9]+$ ]] && [ "$a" -le "$n" ] && NEO_CHOICE=$a
    return 0
  fi

  local cols; cols=$(neo_cols)
  local saved; saved=$(stty -g </dev/tty 2>/dev/null) || saved=""
  _neo_menu_restore() { [ -n "$saved" ] && stty "$saved" </dev/tty 2>/dev/null; printf '\033[?25h' >/dev/tty; }
  trap '_neo_menu_restore; printf "\n" >/dev/tty; exit 130' INT
  stty -echo -icanon min 1 time 0 </dev/tty 2>/dev/null || true
  printf '\033[?25l' >/dev/tty
  printf '\n %s%s%s\n\n' "$_nB" "$title" "$_n0" >/dev/tty

  local first=1 lines=$((n + 2))
  _neo_menu_draw() {
    [ "$first" = 1 ] || printf '\033[%dA' "$lines" >/dev/tty
    first=0
    local j num lab hint pad room
    for j in "${!L[@]}"; do
      if [ "$j" -lt 9 ] || [ "$n" -ge 10 ]; then num=$(printf '%2d ' $((j + 1))); else num='   '; fi
      lab="${L[$j]}"; w=$(_neo_w "$lab"); printf -v pad '%*s' $((lw - w)) ''
      hint=""; room=$((cols - lw - 12))
      [ -n "${H[$j]}" ] && [ "$room" -gt 8 ] && hint="  $(_neo_cut "${H[$j]}" "$room")"
      if [ "$j" -eq "$sel" ]; then
        printf '\033[2K %s❯ %s%s%s%s%s%s%s\n' "$_nA" "$num" "$_n0" "$_nB" "$lab" "$_n0" "$pad" "$_nD$hint$_n0" >/dev/tty
      else
        printf '\033[2K   %s%s%s%s%s%s\n' "$_nD" "$num" "$_n0" "$lab" "$pad" "$_nD$hint$_n0" >/dev/tty
      fi
    done
    printf '\033[2K\n\033[2K %s↑↓ move · Enter select · 1-%d pick · q back%s\n' "$_nD" "$n" "$_n0" >/dev/tty
  }

  local k rest d2
  _neo_menu_draw
  while :; do
    k=""; IFS= read -rsn1 k </dev/tty || { sel=-1; break; }
    case "$k" in
      $'\033')
        rest=""; IFS= read -rsn2 -t 0.25 rest </dev/tty || true
        case "$rest" in
          '[A'|'OA') sel=$(((sel - 1 + n) % n)) ;;
          '[B'|'OB') sel=$(((sel + 1) % n)) ;;
          '[C'|'OC') break ;;
          '[D'|'OD'|'') sel=-1; break ;;
        esac ;;
      k) sel=$(((sel - 1 + n) % n)) ;;
      j) sel=$(((sel + 1) % n)) ;;
      ''|' ') break ;;
      q|Q) sel=-1; break ;;
      [0-9])
        d2=""
        if [ "$n" -ge 10 ] && [ $((k * 10)) -le "$n" ] && [ "$k" != 0 ]; then
          IFS= read -rsn1 -t 0.7 d2 </dev/tty || true
          [[ "$d2" =~ ^[0-9]$ ]] || d2=""
        fi
        if [ "$k$d2" = 0 ]; then sel=-1; break; fi
        if [ "$((10#$k$d2))" -ge 1 ] && [ "$((10#$k$d2))" -le "$n" ]; then sel=$((10#$k$d2 - 1)); _neo_menu_draw; break; fi ;;
    esac
    _neo_menu_draw
  done
  _neo_menu_restore
  trap - INT
  printf '\n' >/dev/tty
  NEO_CHOICE=$((sel + 1))
}

# neo_ask PROMPT [DEFAULT] → answer on stdout. neo_secret PROMPT → hidden answer.
neo_ask() {
  local a=""
  printf '  %s?%s %s%s ' "$_nA" "$_n0" "$1" "${2:+ ${_nD}[$2]${_n0}}" >/dev/tty
  IFS= read -r a </dev/tty || true
  printf '%s' "${a:-${2:-}}"
}
neo_secret() {
  local a=""
  printf '  %s?%s %s ' "$_nA" "$_n0" "$1" >/dev/tty
  IFS= read -rs a </dev/tty || true
  printf '\n' >/dev/tty
  printf '%s' "$a"
}
# neo_confirm QUESTION [y|n] → 0 for yes.
neo_confirm() {
  local d="${2:-n}" hint a
  [ "$d" = y ] && hint="Y/n" || hint="y/N"
  a=$(neo_ask "$1" "$hint")
  [ "$a" = "$hint" ] && a="$d"
  case "$a" in y|Y|yes|YES|بله|آره) return 0 ;; *) return 1 ;; esac
}
neo_pause() { neo_tty && { printf '\n  %sPress Enter to go back%s' "$_nD" "$_n0" >/dev/tty; IFS= read -r _ </dev/tty || true; printf '\n'; }; return 0; }

# neo_ad [PLACEMENT]: the current NeoProject ad in a box; Persian ads are
# right-aligned. Quiet when there is no ad, no network or no python3.
neo_ad() {
  # fetched once per run; menus that redraw show the same ad again
  if [ -n "${_NEO_AD_DONE:-}" ]; then
    [ -n "${_NEO_AD_OUT:-}" ] && printf '%s\n' "$_NEO_AD_OUT"
    return 0
  fi
  _NEO_AD_DONE=1 _NEO_AD_OUT=""
  [ "${NEO_NO_ADS:-0}" = 1 ] && return 0
  command -v curl >/dev/null 2>&1 && command -v python3 >/dev/null 2>&1 || return 0
  local src body=""
  for src in $NEO_ADS_SOURCES; do
    body=$(curl -fsS --max-time 4 "$src?product=$NEO_SLUG&placement=${1:-cli}&mode=rotate" 2>/dev/null) || body=""
    [ -n "$body" ] && break
  done
  [ -n "$body" ] || return 0
  _NEO_AD_OUT=$(NEO_AD_JSON="$body" NEO_AD_COLS="$(neo_cols)" NEO_AD_COLOR="${_nA:+1}" NEO_AD_ACC="${NEO_ACCENT:-44}" \
  python3 - 2>/dev/null <<'PY'
import json, os, re, unicodedata
d = json.loads(os.environ["NEO_AD_JSON"])
ad = d.get("ad") or (d.get("ads") or [None])[0]
if not ad or not str(ad.get("title", "")).strip():
    raise SystemExit
clean = lambda s: re.sub(r"[\x00-\x1f\x7f-\x9f\u202a-\u202e\u2066-\u2069]", " ", str(s or "")).strip()
title, body, btn, url, badge = (clean(ad.get(k)) for k in ("title", "body", "buttonText", "linkUrl", "badge"))
def w(s):
    return sum(0 if unicodedata.category(c) in ("Mn", "Me", "Cf") else 2 if unicodedata.east_asian_width(c) in "WF" else 1 for c in s)
rtl = any("\u0590" <= c <= "\u08ff" or "\ufb1d" <= c <= "\ufefc" for c in title + body + btn)
on = os.environ.get("NEO_AD_COLOR") == "1"
A = f"\033[38;5;{os.environ.get('NEO_AD_ACC', '44')}m" if on else ""
B, D, Z = ("\033[1m", "\033[2m", "\033[0m") if on else ("", "", "")
W = max(30, min(66, int(os.environ.get("NEO_AD_COLS", "80")) - 4))
inner = W - 4
def wrap(s):
    out, line = [], ""
    for word in s.split():
        if line and w(line) + 1 + w(word) > inner:
            out.append(line); line = word
        else:
            line = (line + " " + word).strip()
    if line: out.append(line)
    return out
def row(s, style=""):
    pad = " " * max(0, inner - w(s))
    text = (pad + s) if rtl else (s + pad)
    return f"  {D}│{Z} {style}{text}{Z} {D}│{Z}"
tag = badge or ("آگهی" if rtl else "Sponsored")
head = f" {tag} "
top = f"  {D}╭─{Z}{A}{head}{Z}{D}" + "─" * max(1, W - 3 - w(head)) + f"╮{Z}"
lines = [top, row("")]
lines += [row(x, B) for x in wrap(title)]
lines += [row(x) for x in wrap(body)]
if btn or url:
    lines.append(row(""))
    if btn: lines.append(row(("‹ " + btn + " ›"), A + B))
    if url: lines.append(row(re.sub(r"^https?://", "", url), D))
lines += [row(""), f"  {D}╰" + "─" * (W - 2) + f"╯{Z}"]
print("\n".join(lines))
PY
) || _NEO_AD_OUT=""
  [ -n "$_NEO_AD_OUT" ] && printf '%s\n' "$_NEO_AD_OUT"
  return 0
}
# <<< neo-ui <<<

[ "$(id -u)" -eq 0 ] || die "run as root: curl -fsSL ... | sudo bash"
[ "$(uname -s)" = "Linux" ] || die "NeoExit runs on Linux"

if [ "$UNINSTALL" = 1 ]; then
  systemctl disable --now neoexit 2>/dev/null || true
  rm -f /etc/systemd/system/neoexit.service /usr/local/bin/neoexit
  rm -rf /etc/neoexit /run/neoexit
  systemctl daemon-reload
  ok "NeoExit removed"
  exit 0
fi

# Already installed and someone at the keyboard: the menu. Not from
# NeoTunnel or a script (no terminal), and only if this NeoExit has one.
if [ "$MENU" = 1 ] && [ -x /usr/local/bin/neoexit ] && [ -t 1 ] && { : </dev/tty; } 2>/dev/null; then
  help=$(/usr/local/bin/neoexit </dev/null 2>&1 || true)
  case "$help" in *$'\n  menu '*) exec /usr/local/bin/neoexit menu </dev/tty ;; esac
fi

case "$(uname -m)" in
  x86_64|amd64) ARCH=amd64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  *) die "unsupported CPU $(uname -m) (amd64 and arm64 only)" ;;
esac
NAME="neoexit-linux-$ARCH"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

neo_banner "installer"; echo

if [ -n "$BINARY" ]; then
  step "using local binary $BINARY"
  cp "$BINARY" "$TMP/$NAME"
else
  if [ "$VERSION" = "latest" ]; then
    BASE="https://github.com/$REPO/releases/latest/download"
  else
    BASE="https://github.com/$REPO/releases/download/$VERSION"
  fi
  command -v curl >/dev/null || { apt-get update -qq && apt-get install -y -qq curl >/dev/null; }
  step "downloading $NAME ($VERSION)"
  curl -fL --retry 2 --connect-timeout 15 --progress-bar "$BASE/$NAME" -o "$TMP/$NAME" || die "download failed: $BASE/$NAME"
  if curl -fsSL "$BASE/SHA256SUMS" -o "$TMP/SHA256SUMS" 2>/dev/null; then
    (cd "$TMP" && grep " $NAME\$" SHA256SUMS | sha256sum -c --quiet -) || die "checksum mismatch"
    ok "checksum verified"
  fi
fi

chmod 0755 "$TMP/$NAME"
# 1.4.0 and later set themselves up ("neoexit install"); older ones below.
help=$("$TMP/$NAME" </dev/null 2>&1 || true)
if printf '%s\n' "$help" | grep -q '^  install '; then
  "$TMP/$NAME" install || die "install failed"
  [ -x /usr/local/bin/neotunnel ] && printf '%sNeoTunnel found: its panel manages NeoExit on this server.%s\n\n' "$c_dim" "$c_0"
  neo_ad cli
  exit 0
fi

install -m 0755 "$TMP/$NAME" /usr/local/bin/neoexit
ok "installed $(/usr/local/bin/neoexit version)"

FIRST=0
if [ ! -f /etc/neoexit/config.json ]; then
  FIRST=1
  /usr/local/bin/neoexit init > "$TMP/login.txt"
fi

cat > /etc/systemd/system/neoexit.service <<'EOF'
[Unit]
Description=NeoExit: free exits for AI services
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=/usr/local/bin/neoexit run
Restart=always
RestartSec=3
LimitNOFILE=1048576
RuntimeDirectory=neoexit
RuntimeDirectoryMode=0755

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable neoexit >/dev/null 2>&1
systemctl restart neoexit
ok "service running"

if [ "$FIRST" = 1 ]; then
  cat "$TMP/login.txt"
  printf '%sThe password is shown only now. Forgot it? Run: neoexit password%s\n\n' "$c_dim" "$c_0"
else
  /usr/local/bin/neoexit info
  printf '%sSettings and password kept.%s\n\n' "$c_dim" "$c_0"
fi
[ -x /usr/local/bin/neotunnel ] && printf '%sNeoTunnel found: its panel shows NeoExit on this server.%s\n\n' "$c_dim" "$c_0"
neo_ad cli
exit 0
